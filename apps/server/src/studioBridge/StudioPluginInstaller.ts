export const PLUGIN_FILE_NAME = "SealCodeStudio.rbxmx";
const LOCK_STALE_MS = 60_000;

export class StudioPluginInstallError extends Schema.TaggedError<StudioPluginInstallError>()(
  "StudioPluginInstallError",
  {
    stage: Schema.Literals(["sources", "folder", "lock", "write"]),
    cause: Schema.optional(Schema.Defect()),
  },
) {
  override get message(): string {
    switch (this.stage) {
      case "sources":
        return "This SealCode build has no Studio plugin sources.";
      case "folder":
        return "Could not find or create Roblox Studio's plugins folder.";
      case "lock":
        return "Another SealCode is installing the Studio plugin right now; try again shortly.";
      case "write":
        return "Could not write the Studio plugin file.";
    }
  }
}

export interface PluginSource {
  /** Relative path such as `Handlers/Place.luau`. */
  readonly path: string;
  readonly source: string;
}

const luaString = (value: string): string =>
  `"${[...value]
    .map((char) => (/[A-Za-z0-9 ._:/\-+=]/.test(char) ? char : `\\${String(char.codePointAt(0))}`))
    .join("")}"`;

/** The generated module both sides agree on: protocol, address, pairing key, limits. */
export const configModule = (input: {
  readonly port: number;
  readonly key: string;
  readonly pluginHash: string;
}): string =>
  [
    "-- Generated by SealCode when it installs the plugin. Do not edit.",
    "return {",
    `\tprotocol = ${String(STUDIO_PROTOCOL_VERSION)},`,
    `\tbuild = ${luaString(STUDIO_BRIDGE_BUILD)},`,
    `\tbaseUrl = ${luaString(`http://127.0.0.1:${String(input.port)}`)},`,
    `\tkey = ${luaString(input.key)},`,
    `\tpluginHash = ${luaString(input.pluginHash)},`,
    `\tkeyHeader = ${luaString(PLUGIN_KEY_HEADER)},`,
    `\tpollWaitSeconds = ${String(StudioLimits.pollWaitSeconds)},`,
    `\tproductName = ${luaString("SealCode")},`,
    `\tmutatingEndpoints = { ${[...MUTATING_ENDPOINTS].toSorted().map(luaString).join(", ")} },`,
    "}",
    "",
  ].join("\n");

const xmlText = (value: string): string =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

const cdata = (value: string): string =>
  `<![CDATA[${value.replaceAll("]]>", "]]]]><![CDATA[>")}]]>`;

interface TreeNode {
  readonly name: string;
  readonly className: "Script" | "ModuleScript" | "Folder";
  readonly source?: string;
  readonly children: TreeNode[];
}

/**
 * The plugin as one Roblox XML model: a Script (`Main.server.luau`) holding its modules, with
 * sub-folders for nested paths. Output is deterministic so an unchanged plugin is not rewritten.
 */
export const buildPluginModel = (sources: ReadonlyArray<PluginSource>, config: string): string => {
  const main = sources.find((file) => file.path === "Main.server.luau");
  if (main === undefined) throw new Error("Main.server.luau is missing");
  const root: TreeNode = {
    name: "SealCodeStudio",
    className: "Script",
    source: main.source,
    children: [],
  };
  const files = [
    ...sources.filter((file) => file !== main),
    { path: "Config.luau", source: config },
  ].toSorted((left, right) => left.path.localeCompare(right.path));
  for (const file of files) {
    const segments = file.path.split("/");
    let parent = root;
    for (const folder of segments.slice(0, -1)) {
      let next = parent.children.find(
        (child) => child.name === folder && child.className === "Folder",
      );
      if (next === undefined) {
        next = { name: folder, className: "Folder", children: [] };
        parent.children.push(next);
      }
      parent = next;
    }
    const name = segments.at(-1)!.replace(/\.luau$/, "");
    parent.children.push({ name, className: "ModuleScript", source: file.source, children: [] });
  }
  let referent = 0;
  const render = (node: TreeNode, depth: number): string => {
    const indent = "\t".repeat(depth);
    const properties = [
      `${indent}\t\t<string name="Name">${xmlText(node.name)}</string>`,
      ...(node.source === undefined
        ? []
        : [`${indent}\t\t<ProtectedString name="Source">${cdata(node.source)}</ProtectedString>`]),
    ];
    return [
      `${indent}<Item class="${node.className}" referent="RBX${String(referent++)}">`,
      `${indent}\t<Properties>`,
      ...properties,
      `${indent}\t</Properties>`,
      ...node.children.map((child) => render(child, depth + 1)),
      `${indent}</Item>`,
    ].join("\n");
  };
  return [
    '<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">',
    render(root, 1),
    "</roblox>",
    "",
  ].join("\n");
};

/** Identifies the plugin's code, so a Studio still running an older copy can be told. */
export const pluginHashOf = (sources: ReadonlyArray<PluginSource>): string =>
  NodeCrypto.createHash("sha256")
    .update(sources.map((file) => `${file.path}\n${file.source}`).join("\u0000"))
    .digest("hex")
    .slice(0, 16);

export interface PluginInstallResult {
  readonly path: string;
  readonly pluginHash: string;
  /** The file was replaced: Studio windows already open still run the old copy. */
  readonly changed: boolean;
}

export class StudioPluginInstaller extends Context.Service<
  StudioPluginInstaller,
  {
    readonly install: (input: {
      readonly port: number;
      readonly key: string;
    }) => Effect.Effect<PluginInstallResult, StudioPluginInstallError>;
    /** Removes the plugin, so Studio does not keep looking for a bridge that is turned off. */
    readonly uninstall: Effect.Effect<boolean>;
  }
>()("t3/studioBridge/StudioPluginInstaller") {}

/** How a server build carries the plugin's Luau sources: one JSON file beside its chunks. */
export const StudioPluginBundle = Schema.fromJsonString(
  Schema.Array(Schema.Struct({ path: Schema.String, source: Schema.String })),
);
const decodeBundle = Schema.decodeUnknownEffect(StudioPluginBundle);

const make = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const platform = yield* HostProcess.Platform;
  const env = yield* HostProcess.Environment;
  const home = yield* HostProcess.HomeDirectory;

  /** A server build carries the sources as one JSON file; a checkout reads them from resources. */
  const loadSources = Effect.gen(function* () {
    const bundled = path.resolve(import.meta.dirname, "studio-plugin.json");
    if (yield* fs.exists(bundled).pipe(Effect.orElseSucceed(() => false))) {
      return yield* fs.readFileString(bundled).pipe(Effect.flatMap(decodeBundle));
    }
    const dir = path.resolve(import.meta.dirname, "../../resources/studio-plugin");
    const entries = yield* fs.readDirectory(dir, { recursive: true });
    const sources: PluginSource[] = [];
    for (const entry of entries.toSorted()) {
      if (!entry.endsWith(".luau")) continue;
      sources.push({
        path: entry.split(path.sep).join("/"),
        source: yield* fs.readFileString(path.join(dir, entry)),
      });
    }
    return sources;
  }).pipe(Effect.mapError((cause) => new StudioPluginInstallError({ stage: "sources", cause })));

  const pluginsFolder = Effect.sync(() => {
    const override = env.SEALCODE_STUDIO_PLUGINS_DIR?.trim();
    if (override) return override;
    if (platform === "win32") {
      const local = env.LOCALAPPDATA?.trim();
      return local ? path.join(local, "Roblox", "Plugins") : undefined;
    }
    if (platform === "darwin") return path.join(home, "Documents", "Roblox", "Plugins");
    return undefined;
  });

  const install: StudioPluginInstaller["Service"]["install"] = (input) =>
    Effect.gen(function* () {
      const sources = yield* loadSources;
      const pluginHash = pluginHashOf(sources);
      const model = buildPluginModel(sources, configModule({ ...input, pluginHash }));
      const folder = yield* pluginsFolder;
      if (folder === undefined) return yield* new StudioPluginInstallError({ stage: "folder" });
      yield* fs
        .makeDirectory(folder, { recursive: true })
        .pipe(Effect.mapError((cause) => new StudioPluginInstallError({ stage: "folder", cause })));
      const target = path.join(folder, PLUGIN_FILE_NAME);
      const current = yield* fs.readFileString(target).pipe(Effect.orElseSucceed(() => undefined));
      if (current === model) return { path: target, changed: false, pluginHash };

      // A lock directory keeps two SealCode servers from interleaving their writes.
      const lock = `${target}.lock`;
      const acquired = yield* fs.makeDirectory(lock).pipe(
        Effect.as(true),
        Effect.catch(() =>
          fs.stat(lock).pipe(
            Effect.flatMap((info) =>
              Effect.gen(function* () {
                const modified = Option.getOrUndefined(info.mtime)?.getTime() ?? 0;
                if ((yield* Clock.currentTimeMillis) - modified < LOCK_STALE_MS) return false;
                yield* fs.remove(lock, { recursive: true });
                yield* fs.makeDirectory(lock);
                return true;
              }),
            ),
            Effect.orElseSucceed(() => false),
          ),
        ),
      );
      if (!acquired) return yield* new StudioPluginInstallError({ stage: "lock" });
      return yield* Effect.gen(function* () {
        const temporary = `${target}.${String(process.pid)}.tmp`;
        yield* fs.writeFileString(temporary, model);
        yield* fs.rename(temporary, target);
        return { path: target, changed: true, pluginHash };
      }).pipe(
        Effect.mapError((cause) => new StudioPluginInstallError({ stage: "write", cause })),
        Effect.ensuring(fs.remove(lock, { recursive: true }).pipe(Effect.ignore)),
      );
    });

  const uninstall = Effect.gen(function* () {
    const folder = yield* pluginsFolder;
    if (folder === undefined) return false;
    const target = path.join(folder, PLUGIN_FILE_NAME);
    if (!(yield* fs.exists(target).pipe(Effect.orElseSucceed(() => false)))) return false;
    return yield* fs.remove(target).pipe(
      Effect.as(true),
      Effect.orElseSucceed(() => false),
    );
  });

  return StudioPluginInstaller.of({ install, uninstall });
});

export const layer = Layer.effect(StudioPluginInstaller, make);
